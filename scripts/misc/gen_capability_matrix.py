#!/usr/bin/env python3
"""Generate docs/capability-matrix.md from the MCP operation registry.

The matrix is derived, never hand-written: the registry classifies every registered tool.
Run with --check in CI to detect drift.

Usage:
    python scripts/misc/gen_capability_matrix.py
    python scripts/misc/gen_capability_matrix.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "skills" / "mcp" / "ReverseLabToolsMCP"))

from reverselab_mcp import registry  # noqa: E402

FORMAT_ORDER = ["pe", "elf", "apk", "dex", "web", "pcap", "dotnet", "wasm", "binary", "directory"]
FORMAT_LABELS = {
    "pe": "PE (Windows)",
    "elf": "ELF",
    "apk": "APK",
    "dex": "DEX",
    "web": "Web / HTTP",
    "pcap": "PCAP",
    "dotnet": ".NET",
    "wasm": "WebAssembly",
    "binary": "Generic binary",
    "directory": "Directory / workspace",
}


def generate() -> str:
    specs = registry.native_specs()
    profiles = registry.all_profiles_report()

    by_format: dict[str, list[str]] = {}
    for spec in specs:
        for fmt in spec.target_formats:
            if fmt == "*":
                continue
            by_format.setdefault(fmt, []).append(spec.name)

    lines: list[str] = []
    lines.append("# Capability matrix")
    lines.append("")
    lines.append("<!-- Generated by scripts/misc/gen_capability_matrix.py. Do not edit by hand. -->")
    lines.append("")
    lines.append(
        "This matrix is derived from `reverselab_mcp/registry.py`. Every operation is a native adapter; "
        "some adapters delegate to an optional external CLI. Live tool availability is environment-specific "
        "and is reported by `scripts/misc/lab_healthcheck.py`, not checked in here."
    )
    lines.append("")
    lines.append("## External tools")
    lines.append("")
    lines.append("| Tool | Optional | Used by |")
    lines.append("| --- | --- | --- |")
    lines.append("| `tshark` | yes | `pcap_summary`, `pcap_extract_http` |")
    lines.append("| `ilspycmd` | yes | `dotnet_list_types`, `dotnet_decompile_type` |")
    lines.append("| WABT (`wasm-objdump`, `wasm2wat`) | yes | `wasm_info` |")
    lines.append("")

    lines.append("## Tool profiles")
    lines.append("")
    lines.append("| Profile | Tools | Families | Purpose |")
    lines.append("| --- | --- | --- | --- |")
    for profile in registry.PROFILES:
        report = profiles[profile]
        families = ", ".join(f"{name}:{count}" for name, count in report["families"].items())
        lines.append(
            f"| `{profile}` | {report['total']} | {families} | {registry.PROFILE_DESCRIPTIONS[profile]} |"
        )
    lines.append("")

    lines.append("## Formats")
    lines.append("")
    lines.append("| Format | Native operations | Examples | External engine |")
    lines.append("| --- | --- | --- | --- |")
    for fmt in FORMAT_ORDER:
        names = sorted(by_format.get(fmt, []))
        if not names:
            continue
        examples = ", ".join(f"`{name}`" for name in names[:4])
        external = {
            "pcap": "`tshark` (optional)",
            "dotnet": "`ilspycmd` (optional)",
            "wasm": "WABT (optional)",
        }.get(fmt, "")
        lines.append(f"| {FORMAT_LABELS.get(fmt, fmt)} | {len(names)} | {examples} | {external} |")
    lines.append("")

    lines.append("## Families")
    lines.append("")
    lines.append("| Family | Operations |")
    lines.append("| --- | --- |")
    families: dict[str, list[str]] = {}
    for spec in specs:
        families.setdefault(spec.family, []).append(spec.name)
    for family in sorted(families):
        names = ", ".join(f"`{name}`" for name in sorted(families[family]))
        lines.append(f"| `{family}` | {names} |")
    lines.append("")

    lines.append("## Notes")
    lines.append("")
    lines.append("- `legacy` is the default profile and keeps the pre-registry catalog intact.")
    lines.append("- An absent external tool must produce a `missing_engine` envelope, never a silent empty result.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="docs/capability-matrix.md", help="output path relative to the repo root")
    parser.add_argument("--check", action="store_true", help="exit 1 when the generated file would change")
    args = parser.parse_args()

    text = generate()
    target = (ROOT / args.out).resolve()
    if args.check:
        if not target.exists():
            print(f"missing generated file: {args.out}")
            return 1
        if target.read_text(encoding="utf-8") != text:
            print(f"out of date: {args.out}; run scripts/misc/gen_capability_matrix.py")
            return 1
        print(f"up to date: {args.out}")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
